import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '../..')
const serverPath = path.join(repoRoot, 'mcp/server.ts')
const outputPath = path.join(repoRoot, 'website-v2/src/data/mcpAgentToolCatalog.ts')

const source = fs.readFileSync(serverPath, 'utf8')

function blockBetween(startMarker, endMarker) {
  const start = source.indexOf(startMarker)
  const end = source.indexOf(endMarker, start)
  if (start === -1 || end === -1) {
    throw new Error(`Could not find MCP registry block: ${startMarker}`)
  }
  return source.slice(start, end)
}

let registrySource = ''
registrySource += blockBetween('const ESSENTIAL_TOOL_NAMES', 'const TOOL_CATEGORIES')
registrySource += '\n'
registrySource += blockBetween('const TOOL_CATEGORIES', '// ---------------------------------------------------------------------------\n// Tool definitions')
registrySource += '\n'
registrySource += blockBetween('const TOOLS = [', '// ---------------------------------------------------------------------------\n// Daemon recovery hint')

registrySource = registrySource
  .replace(/const TOOL_CATEGORIES: Record<string, \{ description: string; tools: string\[\] \}> =/, 'const TOOL_CATEGORIES =')
  .replace(/ as const/g, '')
  .replace(/export /g, '')

registrySource += '\nmodule.exports = { ESSENTIAL_TOOL_NAMES, TOOL_CATEGORIES, TOOLS };'

const sandbox = { module: { exports: {} }, exports: {} }
vm.runInNewContext(registrySource, sandbox, { filename: 'mcp-tool-registry.vm.js' })

const { ESSENTIAL_TOOL_NAMES, TOOL_CATEGORIES, TOOLS } = sandbox.module.exports

function titleCase(value) {
  return value
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ')
}

function schemaType(schema) {
  if (!schema || typeof schema !== 'object') return 'unknown'
  if (schema.enum) return `enum<${schema.enum.join(' | ')}>`
  if (schema.type === 'array' && schema.items?.type) return `${schema.items.type}[]`
  return schema.type || (schema.properties ? 'object' : 'unknown')
}

function normalizeParameter(name, schema, required) {
  const nestedSchema = schema?.properties ? schema : schema?.items?.properties ? schema.items : undefined
  return {
    name,
    type: schemaType(schema),
    required,
    description: schema?.description || '',
    enum: Array.isArray(schema?.enum) ? schema.enum : undefined,
    itemType: schema?.items ? schemaType(schema.items) : undefined,
    properties: nestedSchema?.properties
      ? Object.entries(nestedSchema.properties).map(([childName, childSchema]) =>
          normalizeParameter(childName, childSchema, Array.isArray(nestedSchema.required) && nestedSchema.required.includes(childName))
        )
      : undefined,
  }
}

const categoryEntries = Object.entries(TOOL_CATEGORIES).map(([id, category]) => ({
  id,
  label: titleCase(id),
  description: category.description,
  tools: category.tools,
}))

categoryEntries.splice(1, 0, {
  id: 'discovery',
  label: 'Discovery',
  description: 'Lists MCP categories, counts, function names, and full schemas so clients can unlock specialized tools on demand.',
  tools: ['pd_discover'],
})

function categoryForTool(name) {
  return categoryEntries.find((category) => category.tools.includes(name)) ?? categoryEntries.find((category) => category.id === 'discovery')
}

const definitions = TOOLS.map((tool) => {
  const category = categoryForTool(tool.name)
  const required = Array.isArray(tool.inputSchema?.required) ? tool.inputSchema.required : []
  const properties = tool.inputSchema?.properties ?? {}
  return {
    name: tool.name,
    categoryId: category.id,
    categoryLabel: category.label,
    categoryDescription: category.description,
    exposure: ESSENTIAL_TOOL_NAMES.has(tool.name) || tool.name === 'pd_discover' ? 'default' : 'discoverable',
    description: tool.description,
    required,
    parameters: Object.entries(properties).map(([name, schema]) => normalizeParameter(name, schema, required.includes(name))),
    inputSchema: tool.inputSchema,
  }
})

const missing = categoryEntries.flatMap((category) => category.tools).filter((tool) => !definitions.some((definition) => definition.name === tool))
if (missing.length) {
  throw new Error(`Category references missing MCP tools: ${missing.join(', ')}`)
}

const generated = `// Generated by website-v2/scripts/generate-mcp-agent-tool-catalog.mjs from mcp/server.ts.
// Do not hand-edit tool definitions here; update the MCP registry and regenerate.

export interface McpAgentToolParameter {
  name: string
  type: string
  required: boolean
  description: string
  enum?: string[]
  itemType?: string
  properties?: McpAgentToolParameter[]
}

export interface McpAgentToolDefinition {
  name: string
  categoryId: string
  categoryLabel: string
  categoryDescription: string
  exposure: 'default' | 'discoverable'
  description: string
  required: string[]
  parameters: McpAgentToolParameter[]
  inputSchema: Record<string, unknown>
}

export interface McpAgentToolCategory {
  id: string
  label: string
  description: string
  tools: string[]
}

export const MCP_AGENT_TOOL_CATEGORIES: McpAgentToolCategory[] = ${JSON.stringify(categoryEntries, null, 2)}

export const MCP_AGENT_TOOL_DEFINITIONS: McpAgentToolDefinition[] = ${JSON.stringify(definitions, null, 2)}

export const MCP_AGENT_DEFAULT_TOOL_NAMES = ${JSON.stringify(
  definitions.filter((tool) => tool.exposure === 'default').map((tool) => tool.name),
  null,
  2
)}
`

fs.writeFileSync(outputPath, generated)
console.log(`Generated ${definitions.length} MCP tool definitions at ${path.relative(repoRoot, outputPath)}`)
