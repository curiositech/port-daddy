#!/usr/bin/env python3
"""Bind selected Figure Desk images to an accepted PDF without replacing history.

Render only explicitly named fragments, in fresh immutable review slots. Slot
numbers identify images, not Book folios. Existing image files and other figure
pins are never overwritten. The matching converged aux resolves figure labels.

  python3 scripts/harbor-research/refresh_figure_desk_pages.py --expect-sha256 ACCEPTED_SHA --figures STEM ...
  python3 scripts/harbor-research/refresh_figure_desk_pages.py --check
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import fitz

ROOT = Path(__file__).resolve().parents[2]
MAP = Path('docs/harbor-research/exposition/figures/desk-curated/RENDER-PAGES.json')
DESK = Path('docs/harbor-research/exposition/figures/desk')
PDF = Path('website-v2/public/whitepaper/coordination-papers-mega-volume.pdf')
AUX = Path('.cache/whitepaper-build/coordination-papers-mega-volume/coordination-papers-mega-volume.aux')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def image_name(slot):
    return f'p{slot:03d}.jpg'


def image_data(records):
    return '/* GENERATED by refresh_figure_desk_pages.py; immutable image provenance. */\nwindow.REVIEW_IMAGES = ' + json.dumps(records, sort_keys=True, ensure_ascii=False) + ';\n'


def locate(pdf, aux, figures, book_dir):
    from export_book_visual_review import caption_records
    if not aux.with_suffix('.pdf').is_file() or sha(pdf) != sha(aux.with_suffix('.pdf')):
        raise ValueError('Accepted PDF does not match the converged aux sibling PDF')
    records = caption_records(aux.read_text())
    out = {}
    with fitz.open(pdf) as doc:
        names = doc.resolve_names()
        for stem in figures:
            if not re.fullmatch(r'[A-Za-z0-9_.-]+', stem):
                raise ValueError('Invalid fragment identifier: ' + stem)
            labels = re.findall(r'\\label\{(fig:[^}]+)\}', (book_dir / 'figures' / (stem + '.tex')).read_text())
            found = [r for r in records if any(a == label or a.endswith(':' + label) for a in r['labels'] for label in labels)]
            if len(found) != 1:
                raise ValueError(f'{stem}: expected one aux caption, found {len(found)}')
            record = found[0]
            dest = names.get(record['destination'], {})
            page = dest.get('page', -1)
            if page < 0 or doc[page].get_label() != record['folio']:
                raise ValueError('PDF/aux destination mismatch: ' + stem)
            out[stem] = page + 1
    return out


def verify_image(root, slot, record):
    path = root / DESK / 'pages' / image_name(slot)
    if not path.is_file() or sha(path) != record['imageSha256']:
        raise ValueError('Immutable image missing or changed: ' + str(path))


def check(root, pdf):
    mapping = json.loads((root / MAP).read_text())
    records = mapping.get('snapshots', {})
    source_sha = sha(pdf)
    if not records or not mapping.get('snapshotFigures'):
        raise ValueError('No committed snapshot bindings')
    for slot, record in records.items():
        verify_image(root, int(slot), record)
    for stem in mapping.get('snapshotFigures', []):
        record = records.get(str(mapping['pages'].get(stem)))
        if not record or record['sourceSha256'] != source_sha or record.get('figureId') != stem:
            raise ValueError('Current figure image is not bound to accepted PDF: ' + stem)
    generated = root / DESK / 'data/RENDER-SNAPSHOTS.js'
    if not generated.is_file() or generated.read_text() != image_data(records):
        raise ValueError('Snapshot JavaScript is stale')
    return len(mapping.get('snapshotFigures', []))


def refresh(root, pdf, locations):
    if not locations:
        raise ValueError('At least one explicit figure is required')
    mapping_path = root / MAP
    mapping = json.loads(mapping_path.read_text())
    records = mapping.setdefault('snapshots', {})
    pages = root / DESK / 'pages'
    pages.mkdir(parents=True, exist_ok=True)
    source_sha = sha(pdf)
    used = set(mapping['pages'].values()) | {int(k) for k in records}
    used.update(int(p.stem[1:]) for p in pages.glob('p*.jpg') if p.stem[1:].isdigit())
    next_center = (max(used, default=0) // 10 + 1) * 10 + 1
    with fitz.open(pdf) as doc:
        if any(not isinstance(p, int) or not 1 <= p <= len(doc) for p in locations.values()):
            raise ValueError('Figure page outside accepted PDF')
        # Fail on tampered history before producing any new files.
        for slot, record in records.items():
            verify_image(root, int(slot), record)
        for stem, actual in sorted(locations.items()):
            old = mapping['pages'].get(stem)
            bound = records.get(str(old), {})
            if bound.get('sourceSha256') == source_sha and bound.get('pdfPage') == actual and bound.get('figureId') == stem:
                continue
            center = next_center
            next_center += 10
            for offset in (-1, 0, 1):
                physical = actual + offset
                if not 1 <= physical <= len(doc):
                    continue
                slot = center + offset
                target = pages / image_name(slot)
                if target.exists() or str(slot) in records:
                    raise ValueError('Refusing to replace an existing review image: ' + str(slot))
                pix = doc[physical - 1].get_pixmap(dpi=120, alpha=False)
                pix.pil_save(str(target), format='JPEG', quality=90, optimize=True)
                records[str(slot)] = {'pdfPage': physical, 'sourceSha256': source_sha,
                    'imageSha256': sha(target), 'width': pix.width, 'height': pix.height,
                    'pageNumbering': 'physical-1-based'}
                if offset == 0:
                    records[str(slot)]['figureId'] = stem
            mapping['pages'][stem] = center
    mapping['snapshotFigures'] = sorted(set(mapping.get('snapshotFigures', [])) | set(locations))
    mapping['_snapshot_note'] = ('snapshots maps immutable review image slots to their true PDF page and source SHA. '
        'Old images and region-note filenames remain unchanged; slot numbers are not Book pages.')
    mapping_path.write_text(json.dumps(mapping, indent=1, ensure_ascii=False) + '\n')
    generated = root / DESK / 'data/RENDER-SNAPSHOTS.js'
    generated.parent.mkdir(parents=True, exist_ok=True)
    generated.write_text(image_data(records))
    return {stem: mapping['pages'][stem] for stem in locations}



def bundle_snapshot_assets(root, destination):
    """Copy receipted immutable images and their JS without replacing history."""
    root, destination = Path(root), Path(destination)
    mapping = json.loads((root / MAP).read_text())
    records = mapping.get('snapshots', {})
    expected = image_data(records)
    source_js = root / DESK / 'data/RENDER-SNAPSHOTS.js'
    if records and (not source_js.is_file() or source_js.read_text() != expected):
        raise ValueError('Snapshot JavaScript is stale')
    for slot, record in records.items():
        verify_image(root, int(slot), record)
        content = (root / DESK / 'pages' / image_name(int(slot))).read_bytes()
        target = destination / 'pages' / image_name(int(slot))
        if target.exists() and target.read_bytes() != content:
            raise ValueError('Bundle would replace an immutable image: ' + str(target))
        target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists():
            target.write_bytes(content)
    target_js = destination / 'data/RENDER-SNAPSHOTS.js'
    target_js.parent.mkdir(parents=True, exist_ok=True)
    target_js.write_text(expected)
    return len(records)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--figures', nargs='+')
    ap.add_argument('--pdf', type=Path, default=ROOT / PDF)
    ap.add_argument('--aux', type=Path, default=ROOT / AUX)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--expect-sha256', help='accepted PDF digest required for a capture')
    args = ap.parse_args()
    if args.check:
        print(f'Immutable review images verified for {check(ROOT, args.pdf)} figures')
    elif args.figures:
        if not args.expect_sha256 or not re.fullmatch(r'[a-f0-9]{64}', args.expect_sha256):
            ap.error('--figures requires the accepted --expect-sha256 digest')
        if sha(args.pdf) != args.expect_sha256:
            raise ValueError('PDF differs from the explicitly accepted digest; no capture performed')
        locations = locate(args.pdf, args.aux, args.figures, ROOT / 'book')
        print(json.dumps(refresh(ROOT, args.pdf, locations), indent=2))
    else:
        ap.error('choose --figures or --check')


if __name__ == '__main__':
    main()
