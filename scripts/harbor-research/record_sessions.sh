#!/usr/bin/env bash
# Record the terminal sessions the Book prints ("At the terminal" listings).
# Every transcript is produced by running a real tool, or is cut from a
# committed run log, then normalised (ULIDs, timestamps, PIDs, durations) so
# the checked-in text is stable across runs. Usage:
#   scripts/harbor-research/record_sessions.sh            # (re)record all
#   scripts/harbor-research/record_sessions.sh --check    # exit 1 on drift
# Output fragments live under book/figures/session-*.tex and are \input
# by the chapters like figures.
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=book/figures
MODE=${1:-record}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

normalise() { python3 scripts/harbor-research/normalise_session.py; }

wrap() {  # title, transcript file, out file
  {
    echo "% GENERATED by scripts/harbor-research/record_sessions.sh -- do not edit."
    case "$(basename "$3")" in
      session-swk-workunit-check.tex)
        echo "% Reader question: does every work-unit guard exclude a distinct bad execution, or are any guards redundant?"
        echo "% Claim: all six invariants hold with every guard enabled, and disabling each guard exposes a shortest counterexample."
        echo "% Evidence: exhaustive exploration reaches 536 states in the baseline and restored runs, with one mutation witness for every guard [verified, c0_workunit.py]."
        echo "% Must distinguish: the clean baseline and restoration from the six deliberately unsafe mutation runs between them."
        echo "% Grammar: full-width terminal transcript with semantic line breaks; rejected a diagram because the exact commands, counts, and shortest traces are the evidence."
        echo "% Five-second test: the transcript opens and closes with 536 clean states, while every intervening guard-off block names a violated invariant and witness trace."
        echo "% Width: the exact mutation traces use the Book's intentional 6-inch transcript"
        echo "% field; semantic line breaks prevent the listing's continuation mark from"
        echo "% colliding with the trace arrows without shrinking its type."
        ;;
    esac
    echo "\\begin{pdsession}[$1]"
    cat "$2"
    echo "\\end{pdsession}"
  } > "$3"
}

# The lock session of chapter 1 is no longer recorded here. The Book prints a
# recording of its own kernel, harbord, cut into book/excerpts/lock-demo.txt
# by that kernel's tools/excerpts.mjs and set with \pdsessionfile.

# ---- session 2: the work-unit checker and its mutation suite (chapter 1) ----
{
  echo '$ python3 skills/harbor-results/scripts/c0_workunit.py'
  timeout 300 python3 skills/harbor-results/scripts/c0_workunit.py 2>&1 \
    | sed -n '/^BASELINE/,/^Guards restored/p' | sed -E 's/ +$//'
} | normalise > "$TMP/s2.txt"
wrap "the work-unit machine: 536 states, every guard essential" "$TMP/s2.txt" "$TMP/session-swk-workunit-check.tex"

# ---- sessions 3 and 4: model-checker traces, from the committed run logs -----
# TLC is not re-run here (proofs.yml does that); the session is an excerpt of
# the checked-in log, so the printed trace is the one CI reproduces and drifts
# only when the log does. excerpt_trace.py keeps the named states and strips
# wall-clock stamps.
{
  echo '$ java -cp tla2tools.jar tlc2.TLC -config claim_signaling_delta30.cfg claim_signaling.tla'
  python3 scripts/harbor-research/excerpt_trace.py proofs/economics/claim_signaling_delta30.run.log --keep-states 1,2,3,6
} | normalise > "$TMP/s3.txt"
wrap "claim signaling at \\(\\delta = 0.30\\): TLC finds the profitable deviation" "$TMP/s3.txt" "$TMP/session-bc-delta30.tex"

{
  echo '$ java -cp tla2tools.jar tlc2.TLC -config CardRevocation_rollback.cfg CardRevocation.tla'
  python3 scripts/harbor-research/excerpt_trace.py proofs/relay/CardRevocation_rollback.run.log
} | normalise > "$TMP/s4.txt"
wrap "the rollback configuration fails by design" "$TMP/s4.txt" "$TMP/session-fh-rollback.tex"

# ---- session 5: the ProVerif attack trace and its fix (chapter 2) ------------
# ProVerif is not re-run here either (proofs.yml diffs the committed results);
# the session prints the query, the reachable goal and the verdict from the
# committed results of the version-6 model, then the verdict of version 7.
{
  echo '$ proverif analyses/harbor_card_v6_multihop_attack.pv'
  grep -E "^-- Query not event\(Accepted|^goal reachable" analyses/harbor_card_v6_results.txt | head -2
  echo
  echo '  ... derivation, 11 steps, elided; the trace is in analyses/harbor_card_v6_results.txt ...'
  echo
  grep -E "^A trace has been found|^RESULT not event\(Accepted" analyses/harbor_card_v6_results.txt | head -2
  echo
  echo '$ proverif analyses/harbor_card_v7_multihop_fixed.pv'
  grep -E "^RESULT not event\(Accepted" analyses/harbor_card_v7_results.txt | head -1
} | normalise > "$TMP/s5.txt"
wrap "the multi-hop attack on version 6, and version 7 closing it" "$TMP/s5.txt" "$TMP/session-anchor-v6-attack.tex"

# ---- compare or install ----------------------------------------------------
# Kernel sessions (session-swk-*) live beside the kernel's figures; every other
# chapter resolves figures/ under website-v2/public/whitepaper.
status=0
for f in "$TMP"/session-*.tex; do
  b=$(basename "$f")
  case "$b" in session-swk-*) OUT=book/figures;; *) OUT=book/figures;; esac
  if [ "$MODE" = "--check" ]; then
    if ! diff -q "$f" "$OUT/$b" >/dev/null 2>&1; then echo "DRIFT: $OUT/$b"; diff "$OUT/$b" "$f" || true; status=1; fi
  else
    cp "$f" "$OUT/$b"; echo "wrote $OUT/$b"
  fi
done
[ "$MODE" = "--check" ] && [ $status -eq 0 ] && echo "sessions match"
exit $status
