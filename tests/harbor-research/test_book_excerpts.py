"""The code and the runs the Book prints are the files its excerpt manifest pins.

book/excerpts/ is cut from the Book's own kernel by that kernel's
tools/excerpts.mjs, which also checks the files against the kernel's source.
That check cannot run here: the kernel's repository is private. What this
repository can hold is its own half: nobody edits an excerpt by hand, the
Book prints nothing the manifest does not list, and no line is wider than
the column that sets it.
"""
import hashlib
import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BOOK = ROOT / 'book'
EXCERPTS = BOOK / 'excerpts'
LINE_BUDGET = 150  # lines of code one build section may print
LISTING_COLUMN = 66  # characters a listing line holds
TRANSCRIPT_COLUMN = 54  # characters a terminal transcript line holds
CODE = re.compile(r'\\pdexcerpt(?:\[[^\]]*\])?\{([^}]+)\}', re.S)
RUN = re.compile(r'\\pdrun(?:lines)?(?:\[[^\]]*\])?\{([^}]+)\}', re.S)
TRANSCRIPT = re.compile(r'\\pdsessionfile(?:\[[^\]]*\])?\{([^}]+)\}', re.S)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def uncommented(text):
    return '\n'.join(re.split(r'(?<!\\)%', line, maxsplit=1)[0] for line in text.splitlines())


def printed(pattern):
    """Every name the chapters pass to a macro matching `pattern`."""
    sources = sorted(BOOK.glob('*.tex')) + sorted((BOOK / 'additions').glob('*.tex'))
    return [name for source in sources for name in pattern.findall(uncommented(source.read_text()))]


class BookExcerpts(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.manifest = json.loads((EXCERPTS / 'manifest.json').read_text())
        cls.excerpts = {entry['name']: entry for entry in cls.manifest['excerpts']}
        cls.sessions = {entry['name']: entry for entry in cls.manifest['sessions']}

    def test_the_manifest_pins_a_commit(self):
        self.assertEqual(self.manifest['schema'], 1)
        self.assertRegex(self.manifest['commit'], r'^[0-9a-f]{40}$')

    def test_every_file_is_the_one_the_manifest_pins(self):
        for name, entry in self.excerpts.items():
            self.assertEqual(sha256(EXCERPTS / f'{name}.code'), entry['sha256'], f'{name}.code was edited by hand')
        for name, entry in self.sessions.items():
            self.assertEqual(sha256(EXCERPTS / f'{name}.txt'), entry['sha256'], f'{name}.txt was edited by hand')

    def test_each_listing_head_states_the_manifest_lines(self):
        scan = self.manifest['scan'] + '/'
        for name, entry in self.excerpts.items():
            self.assertTrue(entry['path'].startswith(scan), entry['path'])
            data = (EXCERPTS / f'{name}.tex').read_text().splitlines()
            self.assertEqual(len(data), 2, f'{name}.tex')
            self.assertTrue(data[0].startswith('% GENERATED by tools/excerpts.mjs'))
            self.assertEqual(
                data[1],
                '\\pdexcerptdata{%s}{%s}{%d}{%d}{%s}{%s}' % (
                    name, entry['path'][len(scan):], entry['firstLine'], entry['lastLine'],
                    self.manifest['commit'][:9], entry['language']),
            )
            lines = (EXCERPTS / f'{name}.code').read_text().splitlines()
            self.assertEqual(len(lines), entry['lines'])
            self.assertEqual(entry['lastLine'] - entry['firstLine'] + 1, entry['lines'])

    def test_the_directory_holds_nothing_else(self):
        expected = {'manifest.json'}
        expected |= {f'{name}{suffix}' for name in self.excerpts for suffix in ('.code', '.tex')}
        expected |= {f'{name}.txt' for name in self.sessions}
        self.assertEqual({path.name for path in EXCERPTS.iterdir()}, expected)

    def test_the_book_prints_what_the_manifest_lists_and_nothing_else(self):
        self.assertEqual(sorted(printed(CODE)), sorted(self.excerpts))
        self.assertEqual(sorted(set(printed(RUN)) | set(printed(TRANSCRIPT))), sorted(self.sessions))
        self.assertEqual(len(printed(CODE)), len(set(printed(CODE))), 'an excerpt is printed twice')

    def test_no_build_section_prints_more_code_than_its_budget(self):
        # A name opens with its build: "ch01" is Chapter 1's first build
        # section and "ch01b" its second.
        totals = {}
        for name, entry in self.excerpts.items():
            build = name.split('-')[0]
            self.assertRegex(build, r'^ch\d\d[a-z]?$', name)
            totals[build] = totals.get(build, 0) + entry['lines']
        self.assertEqual(totals, self.manifest['printedLines'])
        for build, lines in totals.items():
            self.assertLessEqual(lines, LINE_BUDGET, build)

    def test_no_line_is_wider_than_the_column_that_sets_it(self):
        transcripts = set(printed(TRANSCRIPT))
        for name in self.excerpts:
            for line in (EXCERPTS / f'{name}.code').read_text().splitlines():
                self.assertLessEqual(len(line), LISTING_COLUMN, f'{name}.code: {line}')
        for name in self.sessions:
            column = TRANSCRIPT_COLUMN if name in transcripts else LISTING_COLUMN
            for line in (EXCERPTS / f'{name}.txt').read_text().splitlines():
                self.assertLessEqual(len(line), column, f'{name}.txt: {line}')


if __name__ == '__main__':
    unittest.main()
