describe('HPKE core vs. RFC 9180 official test vector (DHKEM(X25519,HKDF-SHA256)/HKDF-SHA256/AES-256-GCM)', () => {
  const info = fromHex(RFC9180_OFFICIAL_VECTOR.info);
  const skEm = fromHex(RFC9180_OFFICIAL_VECTOR.skEm);
  const pkRm = fromHex(RFC9180_OFFICIAL_VECTOR.pkRm);
  const skRm = fromHex(RFC9180_OFFICIAL_VECTOR.skRm);

  it('KNOWN ANSWER: Encap with the vector\'s fixed ephemeral reproduces enc and shared_secret', () => {
    const { enc, sharedSecret } = hpkeEncapBase(pkRm, skEm);
    expect(hex(enc)).toBe(RFC9180_OFFICIAL_VECTOR.enc);
    expect(hex(sharedSecret)).toBe(RFC9180_OFFICIAL_VECTOR.shared_secret);
  });

  it('KNOWN ANSWER: Decap with the vector\'s recipient secret reproduces the same shared_secret', () => {
    const sharedSecret = hpkeDecapBase(fromHex(RFC9180_OFFICIAL_VECTOR.enc), skRm);
    expect(hex(sharedSecret)).toBe(RFC9180_OFFICIAL_VECTOR.shared_secret);
  });

  it('KNOWN ANSWER: KeySchedule reproduces key_schedule_context, key, base_nonce, exporter_secret', () => {
    const sharedSecret = fromHex(RFC9180_OFFICIAL_VECTOR.shared_secret);
    const ks = hpkeKeyScheduleBase(sharedSecret, info);
    expect(hex(ks.keyScheduleContext)).toBe(RFC9180_OFFICIAL_VECTOR.key_schedule_context);
    expect(hex(ks.key)).toBe(RFC9180_OFFICIAL_VECTOR.key);
    expect(hex(ks.baseNonce)).toBe(RFC9180_OFFICIAL_VECTOR.base_nonce);
    expect(hex(ks.exporterSecret)).toBe(RFC9180_OFFICIAL_VECTOR.exporter_secret);
  });

  it('KNOWN ANSWER: SealBase (fixed ephemeral) reproduces the official AES-256-GCM ciphertext at seq=0', () => {
    // This is the one link the upstream research pass flagged as NOT
    // independently verified in its sandbox (no working AEAD tool). It is
    // exercised here through the real hpkeSealBase/hpkeOpenBase — the exact
    // functions wrapChannelKeyForDevice/unwrapChannelKeyForDevice call —
    // not a parallel reimplementation in the test.
    const first = RFC9180_OFFICIAL_VECTOR.encryptions[0];
    const { enc, ciphertext } = hpkeSealBase(pkRm, info, fromHex(first.aad), fromHex(first.pt), skEm);
    expect(hex(enc)).toBe(RFC9180_OFFICIAL_VECTOR.enc);
    expect(hex(ciphertext)).toBe(first.ct);

    const recovered = hpkeOpenBase(enc, skRm, info, fromHex(first.aad), ciphertext);
    expect(hex(recovered)).toBe(first.pt);
  });

  it('KNOWN ANSWER: OpenBase recovers plaintext directly from the vector\'s own ciphertext (seq=0)', () => {
    const first = RFC9180_OFFICIAL_VECTOR.encryptions[0];
    const recovered = hpkeOpenBase(
      fromHex(RFC9180_OFFICIAL_VECTOR.enc),
      skRm,
      info,
      fromHex(first.aad),
      fromHex(first.ct)
    );
    expect(hex(recovered)).toBe(first.pt);
  });

  it('the vector\'s seq=1 nonce is base_nonce XOR I2OSP(1,12) — ComputeNonce, exercised outside the single-shot API', () => {
    // hpkeSealBase/hpkeOpenBase are single-shot by design (seq is always 0 —
    // see their doc comments), so this file's shipped API never computes a
    // seq!=0 nonce. This test checks the RFC's ComputeNonce formula directly
    // against the vector's seq=1 entry using the derived base_nonce, purely
    // to confirm the module's understanding of the spec is correct — not a
    // code path wrapChannelKeyForDevice/unwrapChannelKeyForDevice exercise.
    const sharedSecret = fromHex(RFC9180_OFFICIAL_VECTOR.shared_secret);
    const { baseNonce } = hpkeKeyScheduleBase(sharedSecret, info);
    const second = RFC9180_OFFICIAL_VECTOR.encryptions[1];
    const computed = Buffer.from(baseNonce);
    computed[computed.length - 1] ^= 0x01; // I2OSP(1, 12) is all zero bytes except the last
    expect(hex(computed)).toBe(second.nonce);
  });

  it('suite ids match RFC 9180 §4.1/§5.1 for this ciphersuite', () => {
    // KEM_SUITE_ID/HPKE_SUITE_ID are module-private; this pins them
    // indirectly by checking that Encap/KeySchedule land on the vector's
    // published outputs, which is only possible if both suite_id
    // constructions are exactly right. Recorded here as a named check
    // rather than leaving it implicit in the tests above.
    const { sharedSecret } = hpkeEncapBase(pkRm, skEm);
    expect(hex(sharedSecret)).toBe(RFC9180_OFFICIAL_VECTOR.shared_secret);
  });
});

