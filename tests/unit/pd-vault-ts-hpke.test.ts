/**
 * HPKE base-mode key wrap (RFC 9180 / ADR-0123 A4-B3) — two independent
 * checks, kept apart deliberately:
 *
 * 1. The low-level HPKE core (LabeledExtract/LabeledExpand, DHKEM
 *    Encap/Decap, KeySchedule, single-shot Seal/Open) against RFC 9180's
 *    own official test-vectors.json entry for DHKEM(X25519,HKDF-SHA256) /
 *    HKDF-SHA256 / AES-256-GCM (mode=0, kem_id=32, kdf_id=1, aead_id=2).
 *    This is bytes this implementation did not generate — the strongest
 *    kind of proof available for a from-scratch primitive.
 *
 * 2. wrapChannelKeyForDevice/unwrapChannelKeyForDevice — port-daddy's own
 *    composition of that core with KeyWrapAad — against a SELF-GENERATED
 *    known-answer vector, same provenance discipline as the Rust crate's
 *    KATs (see core/kernel/pd-vault/src/{keys,seal}.rs test modules): these
 *    bytes came out of THIS implementation and were pasted back in. They
 *    are NOT RFC vectors and not yet cross-checked against the Rust
 *    hpke.rs module — see the file-level report for the values to diff.
 *
 * The RFC9180_OFFICIAL_VECTOR constant below was generated by a script that
 * read https://raw.githubusercontent.com/cfrg/draft-irtf-cfrg-hpke/master/
 * test-vectors.json directly and printed the matching entry's fields as TS
 * source — every hex string here was machine-copied from that JSON, never
 * hand-retyped. That mattered: an earlier hand-transcription of the same
 * vector (an upstream research pass, not this file) turned out to have
 * dropped the trailing hex nibble off nearly every 32-byte field. Re-fetching
 * and diffing byte-for-byte is what caught it — worth remembering before
 * trusting any hand-copied crypto constant, including the ones below.
 */

