    '      sleep "$pd_dw_seconds" 2>/dev/null',
    '      [ -f "$pd_dw_done" ] || : > "$pd_dw_deadline" 2>/dev/null || true',
    '    }',
    '    pd_deadline_watch_stop() {',
    '      if [ -n "$pd_deadline_watch_pid" ]; then',
    '        if command -v pkill >/dev/null 2>&1; then pkill -TERM -P "$pd_deadline_watch_pid" 2>/dev/null || true; fi',
