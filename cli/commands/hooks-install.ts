function commandExists(bin: string): boolean {
  try {
    execFileSync('command', ['-v', bin], { stdio: ['pipe', 'pipe', 'pipe'], shell: '/bin/sh' });
    return true;
  } catch {
    try {
      execFileSync('which', [bin], { stdio: ['pipe', 'pipe', 'pipe'] });
      return true;
    } catch {
      return false;
    }
  }
}

