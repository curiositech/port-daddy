/**
 * pd hooks install — Per-project, daemon-gated coordination hooks for agent CLIs
 *
 * Wires the Giant Squid Harness tentacles into the INTERACTIVE sessions of the
 * agent CLIs on this machine (Claude Code, Codex, Gemini, Antigravity/agy). The
 * hook SHAPES come from one shared source of truth — lib/squid/hook-shape.ts —
 * which the squid headless adapter uses too, so the interactive and headless
 * injectors can never drift.
 *
 * Two guarantees the user asked for:
 *   1. PER PROJECT. Claude/Gemini get project-level config written into the repo
 *      (`<repo>/.claude/settings.json`, `<repo>/.gemini/settings.json`). Codex
 *      (repo-local hooks don't fire interactively — openai/codex#17532) and agy
 *      (home-scoped `~/.gemini/hooks.json`) must be user-level, so they are
 *      constrained at RUNTIME by the gate below.
 *   2. INERT UNLESS PORT DADDY IS RUNNING. Every hook command points at a gate
 *      wrapper, not the tentacle directly. The wrapper no-ops (allow / no
 *      context) unless (a) the pd daemon is alive AND (b) the cwd is inside a
 *      pd-enabled project (a `.portdaddy/` marker on the path). So the hooks do
 *      nothing in non-pd projects or when the daemon is down.
 *
 * Layout under ~/.port-daddy/bin/:
 *   squid/pd-hook-{prompt,pre-tool,post-tool}   <- the real tentacles (copied)
 *   pd-hook-{prompt,pre-tool,post-tool}         <- generated gate wrappers
 * Hook configs point at the gate wrappers.
 *
 * Usage:
 *   pd hooks install            # wire detected CLIs for THIS project (+gated user cfg)
 *   pd hooks install --user     # also write user-level config for claude/gemini
 *   pd hooks list               # detection + wiring status
 *   pd hooks uninstall          # remove Port Daddy hooks from every surface
 */

