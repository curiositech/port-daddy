    '  printf "%s000" "$(date +%s)"',
    '}',
    'pd_debug_lock_acquire() {',
    '  pd_attempt=0',
    '  while ! mkdir "$pd_debug_lock" 2>/dev/null; do',
    '    pd_attempt=$((pd_attempt + 1))',
    '    pd_lock_now=$(date +%s 2>/dev/null || printf 0)',
